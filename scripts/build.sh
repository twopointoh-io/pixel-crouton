#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
root="$(pwd -P)"
archs=()
case "${1:-}" in
  "") archs=("$(uname -m)") ;;
  --universal) archs=(arm64 x86_64) ;;
  *) echo "usage: $0 [--universal]" >&2; exit 2 ;;
esac
build="$(mktemp -d "${TMPDIR:-/tmp}/pixel-crouton-build.XXXXXX")"
trap 'rm -rf -- "$build"' EXIT
bundle="$build/Pixel Crouton.app"
mkdir -p "$bundle/Contents/MacOS" "$bundle/Contents/Resources" "$root/dist"
cp Assets/Info.plist "$bundle/Contents/"
xcrun swift scripts/DrawIcon.swift "$bundle/Contents/Resources/AppIcon.icns"
bins=()
for arch in "${archs[@]}"; do
    bin="$build/PixelCrouton-$arch"
    xcrun swiftc -swift-version 6 -O -target "$arch-apple-macosx14.0" Sources/*.swift -o "$bin"
    bins+=("$bin")
done
if (( ${#bins[@]} == 1 )); then
    cp "${bins[0]}" "$bundle/Contents/MacOS/PixelCrouton"
else
    xcrun lipo -create "${bins[@]}" -output "$bundle/Contents/MacOS/PixelCrouton"
fi
codesign --force --sign - "$bundle"
codesign --verify --strict "$bundle"
out="$root/dist/Pixel Crouton.app"
# Replace only the bundle generated by this script, never any installation elsewhere.
if [[ -e "$out" ]]; then
    mv "$out" "$build/previous.app"
fi
if ! mv "$bundle" "$out"; then
    [[ ! -e "$build/previous.app" ]] || mv "$build/previous.app" "$out"
    exit 1
fi
printf 'Built: %s\n' "$out"
